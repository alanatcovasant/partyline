#!/usr/bin/env bash
# One-command, fully-automated deploy: provisions the autoscale Lakebase (idempotent),
# builds the ops SPA, and deploys the bundle. No manual provisioning steps.
#
# Usage:  ./deploy.sh [profile] [target]
#         ./deploy.sh dev-eastus2 dev-eastus2      # defaults
set -euo pipefail

PROFILE="${1:-dev-eastus2}"
TARGET="${2:-dev-eastus2}"
# Must match ENDPOINT_NAME in resources/covasant_partyline_app.app.yml (config.env).
ENDPOINT_NAME="${ENDPOINT_NAME:-projects/partyline/branches/production/endpoints/primary}"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

echo "==> 0/3 Stamping build version"
BUILD_TS="$(date -u +%Y%m%d.%H%M)"
GIT_COMMIT="$(git rev-parse --short=8 HEAD 2>/dev/null || echo 'unknown')"
GIT_DIRTY="$(git diff --quiet 2>/dev/null && echo '' || echo '.dirty')"
BUILD_HOST="$(hostname 2>/dev/null || echo 'unknown')"
# Match the actual `__version__ = "..."` assignment — a bare grep for __version__ also
# hit the comment/import lines above it, so head -1 grabbed a comment (garbled version).
BASE_VERSION="$(grep -E '^[[:space:]]*__version__[[:space:]]*=' covasant-partyline/app/__init__.py | head -1 | sed 's/.*"\(.*\)".*/\1/' | sed 's/\.dev.*//')"
FULL_VERSION="${BASE_VERSION}.dev${BUILD_TS}"

cat > covasant-partyline/app/__version__.py <<EOF
"""Build metadata — auto-generated by deploy.sh. Do not edit."""
__version__ = "${FULL_VERSION}"
__build_timestamp__ = "${BUILD_TS}"
__git_commit__ = "${GIT_COMMIT}${GIT_DIRTY}"
__build_host__ = "${BUILD_HOST}"
EOF
echo "    version=${FULL_VERSION} commit=${GIT_COMMIT}${GIT_DIRTY} host=${BUILD_HOST}"

echo "==> 1/3 Provisioning Lakebase ($ENDPOINT_NAME) on profile $PROFILE"
ENDPOINT_NAME="$ENDPOINT_NAME" DATABRICKS_CONFIG_PROFILE="$PROFILE" \
  python scripts/provision_lakebase.py

echo "==> 1.5/3 Migrating schema as owner (owner-only DDL the app SP can't run)"
# The app connects as its service principal, which does NOT own the partyline tables, so
# ALTER/CREATE INDEX from the app's init_schema are skipped. Run that DDL here as the
# deploying user (the owner) BEFORE the app restarts, so schema changes land on deployed
# instead of crash-looping the app. Idempotent; no-op on a first-ever deploy. See
# docs/adr/2026-07-11-conversation-threading-and-search.md.
ENDPOINT_NAME="$ENDPOINT_NAME" APP_NAME="mcp-covasant-partyline" DATABRICKS_CONFIG_PROFILE="$PROFILE" \
  python scripts/migrate_schema.py

echo "==> 2/4 Building ops SPA"
# --include=dev: an ambient NODE_ENV=production (set on some machines) makes npm skip
# devDependencies, so tsc/vite vanish and the build dies with "tsc is not recognized".
( cd covasant-partyline/client && npm install --include=dev && npm run build )

echo "==> 2.5/4 Packaging VS Code extension for download"
# Build the extension and host it from the SPA's static dir so teammates can install it
# straight from the app (<app-url>/partyline-extension-latest.vsix). Must run AFTER the
# SPA build — vite empties client/dist on build, which would otherwise wipe the .vsix.
(
  cd editors/vscode
  npm install --include=dev
  npm run compile
  # --allow-missing-repository: the manifest has no `repository` field, and without this
  # flag vsce errors in a non-interactive shell (set -e would then abort the deploy).
  # `printf 'y\n' |`: there is no LICENSE file, so vsce still PROMPTS ("Do you want to
  # continue? [y/N]") in a TTY and stalls the deploy waiting on stdin. Feed it 'y' so the
  # packaging stays fully hands-off. (.vscodeignore silences the other, non-blocking warning.)
  # NOTE: use printf, NOT `yes` — `yes` is an infinite writer that gets SIGPIPE-killed
  # (exit 141) when vsce closes stdin, and `set -o pipefail` (line 7) would then make the
  # whole pipeline fail and abort the deploy right after packaging. `printf` writes two
  # bytes, exits 0, and lets vsce's real exit code propagate through the pipe.
  printf 'y\n' | npx --yes @vscode/vsce package --allow-missing-repository
)
EXT_VSIX="$(ls -t editors/vscode/covasant-partyline-*.vsix | head -1)"
EXT_VER="$(basename "$EXT_VSIX" | sed -E 's/covasant-partyline-(.*)\.vsix/\1/')"
mkdir -p covasant-partyline/client/dist
cp "$EXT_VSIX" "covasant-partyline/client/dist/$(basename "$EXT_VSIX")"
cp "$EXT_VSIX" covasant-partyline/client/dist/partyline-extension-latest.vsix
echo "    hosted extension v${EXT_VER} -> /partyline-extension-latest.vsix"

echo "==> 2.7/4 Packaging Python client wheel + install scripts for download"
# Build the client wheel straight into the served dir. --no-deps: only our wheel (deps are
# resolved from PyPI at install time). A manifest file lets install.sh fetch the current
# versioned wheel (pip can't install a non-versioned '*-latest.whl' name).
python -m pip wheel ./partyline-client --no-deps -w covasant-partyline/client/dist
CLIENT_WHL="$(ls -t covasant-partyline/client/dist/covasant_partyline-*.whl | head -1)"
basename "$CLIENT_WHL" > covasant-partyline/client/dist/partyline-client-latest.txt
cp install.sh install.ps1 covasant-partyline/client/dist/
echo "    hosted client wheel $(basename "$CLIENT_WHL") + install.sh/install.ps1"

echo "==> 2.8/4 Publishing using-partyline skill for agents to fetch"
# Snapshot the canonical skill markdown (single source of truth: the plugin skill file)
# next to the app package, where the /skills/using-partyline.md route reads it. It is
# gitignored and force-synced via databricks.yml sync.include as a single explicit file —
# the same proven pattern as __version__.py. (Do NOT drop it under client/dist: dist is
# gitignored, and bundle sync won't discover a brand-new subdirectory created under it.)
cp partyline-plugin/skills/using-partyline/SKILL.md covasant-partyline/app/using-partyline.md
echo "    hosted skill -> /skills/using-partyline.md"

echo "==> 3/6 Provisioning example-job service principal (before bundle deploy)"
# Order matters: the job's prod run_as binds to this SP (databricks.yml override), so the SP
# must exist BEFORE the bundle deploy that registers the job — otherwise a first-ever prod
# deploy would bind run_as to an empty/nonexistent SP. SP creation is app-independent (account
# SCIM + workspace SP + secret scope), so it safely precedes the app deploy; only the CAN_USE
# grant (step 6) needs the app to exist. Idempotent no-op on reruns; prints the applicationId
# as its last stdout line. SP creation needs account SCIM rights; if unavailable this fails
# loudly (a real prerequisite, not a UI step).
SP_APP_ID="$(DATABRICKS_CONFIG_PROFILE="$PROFILE" python scripts/provision_partyline_sp.py | tail -1)"
echo "    example job SP applicationId=${SP_APP_ID}"

echo "==> 4/6 Deploying bundle (target=$TARGET)"
# Pass the SP applicationId so prod's run_as override resolves to the real SP. In dev the
# override is absent, so the --var is harmless (the job runs as the deploying user).
databricks bundle deploy -t "$TARGET" --profile "$PROFILE" \
  --var="partyline_sp_app_id=${SP_APP_ID}"

echo "==> 5/6 Restarting app"
databricks bundle run covasant_partyline -t "$TARGET" --profile "$PROFILE"

echo "==> 6/6 Granting example-job SP CAN_USE on the app"
# The grant needs the app to exist (steps 4–5 above). Idempotent no-op on reruns.
DATABRICKS_CONFIG_PROFILE="$PROFILE" APP_NAME="mcp-covasant-partyline" \
  PARTYLINE_SP_APP_ID="$SP_APP_ID" python scripts/grant_app_access.py

echo "==> Done. App + example job deployed (version=${FULL_VERSION})."
